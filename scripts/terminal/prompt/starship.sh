#!/usr/bin/env bash
# Prints a Starship config for an AnoShell prompt style (apply-terminal.sh writes it to
# generated/terminal/starship.toml; your own starship.toml is never read or changed).
# starship.sh <segments|minimal> <p1bg> <p1fg> <p2bg> <p2fg> <p3bg> <p3fg> <error>
set -euo pipefail
style=$1 p1=$2 p1f=$3 p2=$4 p2f=$5 p3=$6 p3f=$7 er=$8
echo "# Generated by AnoShell (terminal.prompt = $style) from the palette."
echo "add_newline = false"
if [[ "$style" == minimal ]]; then
    cat <<T
format = "\$directory\$character"

[directory]
style = "bold"
format = "[\$path](\$style) "

[character]
success_symbol = "[❯](bold $p1)"
error_symbol = "[❯](bold $er)"
T
else
    cat <<T
format = "[ \$username ](bg:$p1 fg:$p1f)[](fg:$p1 bg:$p2)\$directory[](fg:$p2 bg:$p3)\$git_branch[](fg:$p3) \$character"

[username]
show_always = true
style_user = "bg:$p1 fg:$p1f"
style_root = "bg:$p1 fg:$p1f"
format = "[\$user](\$style)"

[directory]
style = "bg:$p2 fg:$p2f"
format = "[ \$path ](\$style)"

[git_branch]
style = "bg:$p3 fg:$p3f"
format = "[ \$branch ](\$style)"

[character]
success_symbol = ""
error_symbol = "[✘](fg:$er)"
T
fi
