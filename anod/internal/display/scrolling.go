package display

import (
	"encoding/json"
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

// Scrolling workspaces (scrolling.*; Settings → Workspaces), written into the
// managed files. Hyprland: chosen workspaces use its built-in scrolling layout;
// niri always scrolls; mango: chosen tags use its scroller layout. Per-app
// column widths on all three.

// Scrolling is what the managed files need from scrolling.*.
type Scrolling struct {
	Workspaces  []ScrollWorkspace
	ColumnWidth float64 // 0: the compositor's own default
	Apps        []ScrollApp
}

// ScrollWorkspace is one workspace (Hyprland id, mango tag) that scrolls.
type ScrollWorkspace struct {
	ID        int
	Direction string // right, left, down, up
}

// ScrollApp is a per-app column width (fraction of the screen width).
type ScrollApp struct {
	App   string // class / app id
	Width float64
}

var appIDRe = regexp.MustCompile(`^[A-Za-z0-9._-]{1,128}$`)

// CleanScrolling drops entries that can't be written safely or make no sense
// (unknown direction, bad app id, width outside 0.1–1) and duplicates.
func CleanScrolling(s Scrolling) Scrolling {
	var out Scrolling
	if s.ColumnWidth >= 0.1 && s.ColumnWidth <= 1 {
		out.ColumnWidth = s.ColumnWidth
	}
	seen := map[int]bool{}
	for _, w := range s.Workspaces {
		switch w.Direction {
		case "":
			w.Direction = "right"
		case "right", "left", "down", "up":
		default:
			continue
		}
		if w.ID < 1 || w.ID > 99 || seen[w.ID] {
			continue
		}
		seen[w.ID] = true
		out.Workspaces = append(out.Workspaces, w)
	}
	apps := map[string]bool{}
	for _, a := range s.Apps {
		if !appIDRe.MatchString(a.App) || a.Width < 0.1 || a.Width > 1 || apps[a.App] {
			continue
		}
		apps[a.App] = true
		out.Apps = append(out.Apps, a)
	}
	return out
}

// appRegex anchors an app id and escapes its dots.
func appRegex(app string) string { return "^" + strings.ReplaceAll(app, ".", `\.`) + "$" }

func num(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

// hyprRuleName names an app's rule so it can be disabled at runtime.
func hyprRuleName(app string) string { return "ano-scroll-" + app }

func hyprScrolling(s *Scrolling) string {
	if s == nil {
		return ""
	}
	var b strings.Builder
	if s.ColumnWidth > 0 {
		b.WriteString("hl.config({ scrolling = { column_width = " + num(s.ColumnWidth) + " } }) -- scrolling.columnWidth\n")
	}
	for _, w := range s.Workspaces {
		fmt.Fprintf(&b, "hl.workspace_rule({ workspace = \"%d\", layout = \"scrolling\", layout_opts = { direction = \"%s\" } }) -- scrolling.workspaces\n", w.ID, w.Direction)
	}
	for _, a := range s.Apps {
		fmt.Fprintf(&b, "hl.window_rule({ name = \"%s\", match = { class = \"%s\" }, scrolling_width = %s }) -- scrolling.apps\n",
			hyprRuleName(a.App), luaEscape(appRegex(a.App)), num(a.Width))
	}
	return b.String()
}

// hyprScrollingUndo is the live part a Hyprland config reload would do: workspaces
// no longer listed go back to the default layout and dropped apps' rules are disabled.
func hyprScrollingUndo(prev, cur *Scrolling, defaultLayout string) string {
	if prev == nil {
		return ""
	}
	keepWs, keepApp := map[int]bool{}, map[string]bool{}
	if cur != nil {
		for _, w := range cur.Workspaces {
			keepWs[w.ID] = true
		}
		for _, a := range cur.Apps {
			keepApp[a.App] = true
		}
	}
	if defaultLayout == "" {
		defaultLayout = "dwindle"
	}
	var b strings.Builder
	for _, w := range prev.Workspaces {
		if !keepWs[w.ID] {
			fmt.Fprintf(&b, "hl.workspace_rule({ workspace = \"%d\", layout = \"%s\" })\n", w.ID, luaEscape(defaultLayout))
		}
	}
	for _, a := range prev.Apps {
		if !keepApp[a.App] {
			fmt.Fprintf(&b, "hl.window_rule({ name = \"%s\", match = { class = \"%s\" }, scrolling_width = %s }):set_enabled(false)\n",
				hyprRuleName(a.App), luaEscape(appRegex(a.App)), num(a.Width))
		}
	}
	return b.String()
}

func niriScrolling(s *Scrolling) string {
	if s == nil {
		return ""
	}
	var b strings.Builder
	if s.ColumnWidth > 0 {
		b.WriteString("layout { // scrolling.columnWidth\n    default-column-width { proportion " + num(s.ColumnWidth) + "; }\n}\n")
	}
	for _, a := range s.Apps {
		b.WriteString("window-rule { // scrolling.apps\n    match app-id=r#\"" + appRegex(a.App) + "\"#\n    default-column-width { proportion " + num(a.Width) + "; }\n}\n")
	}
	return b.String()
}

// MangoScrolling is the whole mango managed file (source_optional'd from config.conf).
func MangoScrolling(s *Scrolling) string {
	var b strings.Builder
	b.WriteString("# Generated by anod (Settings → Workspaces). Do not edit; source_optional'd from config.conf.\n")
	if s == nil {
		return b.String()
	}
	if s.ColumnWidth > 0 {
		b.WriteString("scroller_default_proportion=" + num(s.ColumnWidth) + "\n")
	}
	for _, w := range s.Workspaces {
		layout := "scroller"
		if w.Direction == "down" || w.Direction == "up" {
			layout = "vertical_scroller"
		}
		fmt.Fprintf(&b, "tag_rule=id:%d,layout_name:%s\n", w.ID, layout)
	}
	for _, a := range s.Apps {
		b.WriteString("window_rule=scroller_proportion:" + num(a.Width) + ",app_id:" + appRegex(a.App) + "\n")
	}
	return b.String()
}

// SeedScrolling records the rules the compositor already has (it read the
// managed file at its start), so a later change can undo what was dropped.
func (s *Service) SeedScrolling() {
	if s.Scrolling != nil {
		s.mu.Lock()
		s.scrolled = s.Scrolling()
		s.mu.Unlock()
	}
}

// RefreshScrolling rewrites the managed file (niri reloads it itself) and, on
// Hyprland, applies the change live with `hyprctl eval`: what a config reload
// would do, without one.
func (s *Service) RefreshScrolling() error {
	if err := s.Refresh(); err != nil {
		return err
	}
	if s.Backend.Name() != "hyprland" || s.Scrolling == nil {
		return nil
	}
	cur := s.Scrolling()
	s.mu.Lock()
	prev := s.scrolled
	s.scrolled = cur
	s.mu.Unlock()
	layout := "dwindle"
	if h, ok := s.Backend.(Hyprland); ok {
		if out, err := h.run("-j", "getoption", "general:layout"); err == nil {
			var v struct {
				Str string `json:"str"`
			}
			if json.Unmarshal(out, &v) == nil && appIDRe.MatchString(v.Str) {
				layout = v.Str
			}
		}
	}
	lua := hyprScrollingUndo(prev, cur, layout) + hyprScrolling(cur)
	if lua == "" {
		return nil
	}
	return s.exec("hyprctl", "eval", lua)
}

// WriteFile writes a managed file atomically (its folder created if missing).
func WriteFile(path, text string) error { return writeAtomic(path, text) }
