// keybinds-import (dev tool) builds anod's default keybind set from the binds
// bundled in ano/external/ and writes a report of where the Hyprland and
// niri sets disagree. Re-run whenever external/ changes:
//
//	go run ./cmd/keybinds-import            (from ano/anod; needs lua)
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"ano/anod/internal/keybinds"
)

func main() {
	ext := filepath.Join("..", "external")
	hp := filepath.Join(ext, "hyprland", "hyprland.lua")
	h, err := keybinds.ReadHyprland(hp)
	check(err)
	n, err := keybinds.ReadNiri(filepath.Join(ext, "niri", "ano.kdl"))
	check(err)
	merged, conflicts := keybinds.Merge(h, n)
	src, err := os.ReadFile(hp)
	check(err)

	out := struct {
		Comment string          `json:"_comment"`
		Helpers string          `json:"hyprlandHelpers"`
		Binds   []keybinds.Bind `json:"binds"`
	}{"Generated by cmd/keybinds-import from ano/external; do not edit.", keybinds.Helpers(string(src), merged), merged}
	b, _ := json.MarshalIndent(out, "", "  ")
	check(os.WriteFile(filepath.Join("internal", "keybinds", "defaults.json"), append(b, '\n'), 0o644))

	var r strings.Builder
	fmt.Fprintf(&r, "# Keybind import report\n\nGenerated by `go run ./cmd/keybinds-import` from `ano/external/`.\n\n")
	fmt.Fprintf(&r, "Read %d Hyprland binds and %d niri binds; the default set has %d.\n\n", len(h), len(n), len(merged))
	fmt.Fprintf(&r, "## Chords the two sets disagree on (%d)\n\nThe rule (spec keybinds): Hyprland's bind wins, unless it only exists on Hyprland.\n\n| Chord | Hyprland | niri | Outcome |\n|---|---|---|---|\n", len(conflicts))
	for _, c := range conflicts {
		fmt.Fprintf(&r, "| `%s` | %s | %s | %s |\n", c.Chord, md(c.Hyprland), md(c.Niri), c.Outcome)
	}
	newOn := func(comp string, from []keybinds.Bind) {
		var rows []string
		for _, x := range merged {
			if !x.On(comp) {
				continue
			}
			had := false
			for _, y := range from {
				if y.Key() == x.Key() {
					had = true
					break
				}
			}
			if !had {
				rows = append(rows, fmt.Sprintf("| `%s` | %s |", x.Chord, md(x.Describe())))
			}
		}
		fmt.Fprintf(&r, "\n## New on %s (%d)\n\nBinds the other compositor had on a chord this one left free.\n\n| Chord | Action |\n|---|---|\n%s\n", comp, len(rows), strings.Join(rows, "\n"))
	}
	newOn("hyprland", h)
	newOn("niri", n)
	check(os.WriteFile(filepath.Join("internal", "keybinds", "import-report.md"), []byte(r.String()), 0o644))
	fmt.Printf("defaults.json: %d binds; %d conflicts (internal/keybinds/import-report.md)\n", len(merged), len(conflicts))
}

func md(s string) string { return "`" + strings.ReplaceAll(s, "|", "\\|") + "`" }

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "keybinds-import:", err)
		os.Exit(1)
	}
}
