// keybinds-import (dev tool) reports what `ano keybinds migrate` would do
// with a pair of compositor configs: which of their binds stay as the user's
// (chords the curated set leaves free) and which the curated set replaces.
// The curated set itself (internal/keybinds/defaults.json) is edited by hand.
//
//	go run ./cmd/keybinds-import [hyprland.lua niri.kdl]   (from ano/anod; needs lua)
//
// Without arguments it reads the configs bundled in ano/external/.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"ano/anod/internal/keybinds"
)

func main() {
	hp := filepath.Join("..", "external", "hyprland", "hyprland.lua")
	np := filepath.Join("..", "external", "niri", "ano.kdl")
	if len(os.Args) == 3 {
		hp, np = os.Args[1], os.Args[2]
	}
	d, err := keybinds.LoadDefaults()
	check(err)
	tmp, err := os.MkdirTemp("", "keybinds-import")
	check(err)
	defer os.RemoveAll(tmp)
	res, err := keybinds.Migrate(keybinds.Paths{HyprMain: hp, NiriMain: np, Overrides: filepath.Join(tmp, "keybinds.json")}, d, time.Now(), true)
	check(err)

	var kept, replaced []string
	for _, l := range res.Report {
		if strings.HasPrefix(l, "kept ") {
			kept = append(kept, "- "+l)
		} else {
			replaced = append(replaced, "- "+l)
		}
	}
	var r strings.Builder
	fmt.Fprintf(&r, "# Keybind migration report\n\nGenerated by `go run ./cmd/keybinds-import` for `%s` and `%s`.\n\n", hp, np)
	fmt.Fprintf(&r, "The curated set has %d binds. On a chord it binds, it wins; your binds on chords it leaves free are kept.\n\n", len(d.Binds))
	fmt.Fprintf(&r, "## Replaced by the curated set (%d)\n\n%s\n\n## Kept as yours (%d)\n\n%s\n", len(replaced), strings.Join(replaced, "\n"), len(kept), strings.Join(kept, "\n"))
	check(os.WriteFile(filepath.Join("internal", "keybinds", "import-report.md"), []byte(r.String()), 0o644))
	fmt.Printf("%d replaced, %d kept (internal/keybinds/import-report.md)\n", len(replaced), len(kept))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "keybinds-import:", err)
		os.Exit(1)
	}
}
